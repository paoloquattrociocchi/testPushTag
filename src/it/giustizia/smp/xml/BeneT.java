public class BeneT extends BeneBase {

	private String altriOggettiDescr;
	private Animali animali;
	private Azienda azienda;
	private Finanziario finanziario;
	private Immateriale immateriale;
	private Immobile immobile;
	private Collezioni collezioni;
	private Veicolo veicolo;

	public String getAltriOggettiDescr() {
		return altriOggettiDescr;
	}

	public void setAltriOggettiDescr(String altriOggettiDescr) {
		this.altriOggettiDescr = altriOggettiDescr;
	}

	public Animali getAnimali() {
		return animali;
	}

	public void setAnimali(Animali animali) {
		this.animali = animali;
	}

	public Azienda getAzienda() {
		return azienda;
	}

	public void setAzienda(Azienda azienda) {
		this.azienda = azienda;
	}

	public Finanziario getFinanziario() {
		return finanziario;
	}

	public void setFinanziario(Finanziario finanziario) {
		this.finanziario = finanziario;
	}

	public Immateriale getImmateriale() {
		return immateriale;
	}

	public void setImmateriale(Immateriale immateriale) {
		this.immateriale = immateriale;
	}

	public Immobile getImmobile() {
		return immobile;
	}

	public void setImmobile(Immobile immobile) {
		this.immobile = immobile;
	}

	public Collezioni getCollezioni() {
		return collezioni;
	}

	public void setCollezioni(Collezioni collezioni) {
		this.collezioni = collezioni;
	}

	public Veicolo getVeicolo() {
		return veicolo;
	}

	public void setVeicolo(Veicolo veicolo) {
		this.veicolo = veicolo;
	}

}
